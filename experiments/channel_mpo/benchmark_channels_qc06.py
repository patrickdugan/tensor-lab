"""Exploratory cross-channel QC-06 test on dephasing and amplitude damping.

Use the same uniform-env6 final-entry budget per case; unlike the primary
pinned depolarizing experiment, budgets vary by channel and are generated by
an online baseline here. This is an exploratory transfer check.
"""
from __future__ import annotations
import argparse,csv
from pathlib import Path
from benchmark_qc06 import run_case


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--seeds',default='3,4,5')
    ap.add_argument('--output',type=Path,default=Path('qc06_other_channels.csv'))
    a=ap.parse_args()
    rows=[]
    for channel in ('dephasing','amplitude_damping'):
        for n in (6,8):
            for p in (.2,.5):
                for seed in map(int,a.seeds.split(',')):
                    x=run_case(n,6,seed,p,12,6,12,True,channel)
                    rows.append(x)
                    print(f'{channel} n={n} p={p} seed={seed} delta={x["distance_delta"]:+.5f}',flush=True)
    with a.output.open('w',newline='') as f:
        w=csv.DictWriter(f,fieldnames=list(rows[0]));w.writeheader();w.writerows(rows)
    print('saved',a.output)


if __name__=='__main__':main()
